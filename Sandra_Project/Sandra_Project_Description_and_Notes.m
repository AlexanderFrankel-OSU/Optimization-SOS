For the Sandra Project, I investigated some exciting properties of the
Lorenz '63 system, including using data assimilation based off of initial
data (which was generated via the Adams-Bashforth method). The files have
been vastly simplified and cleaned up.

The main functions I used were the initmatrix, DAadbash, and adbash (which
is now obsolete because of DAadbash). One change I made to the
DAadbash function was to make it detect which version it should run---regular 
Adams-Bashforth, or with data assimilation. If it detects less than two variables, 
it tries to run regular adbash. If there's two or more, it tries to run data-assimilated
Adams-Bashforth, using the second variable as the "data" to nudge the model
in the right direction.

The initmatrix function was made to make it easy to reset the large
matrices I was using to store the data generated by Adams-Bashforth. 


A description of some of the problems I dealt with:

First, I wrote the code for the data assimilated Adams-Bashforth method,
which Dr. Carlson caught.

The way I was coding was extremely slow. Having to use initmatrix for
everything was better than before (where I would rewrite a function for it
every time), but still was unnecessary. I really just wanted to run one
script with supporting functions that could show the log of absolute error
between the data and the model. However, I've had trouble doing this.
There's a reason I'm writing this for the second time and a worrying Github
commit message was left.

I was at one point using mu values that were too high (though they did not
violate the CFL condition). The overarching project is about finding
minimal mu anyways; larger mu are unnecessary, and will amplify noise.

Aside from issues I've had:

To run the EvoScript with different ux, uy, uz, you unfortunately need to
change them and save the Sandra_Variables.m and then run EvoScript. This is
not ideal, but it does work. Machine precision in MATLAB corresponds to
about 53 bits, which means about 15 digits in base 10. Hopefully, the
difference would converge to machine zero. Currently, they've been
converging to around 10^-12 to 10^-14.

